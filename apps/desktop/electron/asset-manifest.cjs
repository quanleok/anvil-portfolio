const fs = require("node:fs/promises");
const path = require("node:path");
const { atomicWriteFile } = require("./atomic-write.cjs");

const ASSET_MANIFEST_PATH = path.join("assets", "INDEX.md");
const ASSET_MANIFEST_SECTIONS = ["characters", "locations", "props", "keyframes", "audio", "library"];

function normalizePath(value) {
  return String(value || "").replace(/\\/g, "/").replace(/^\/+/, "").trim();
}

function displayName(entry) {
  return String(entry?.name || entry?.title || entry?.id || "Untitled").trim();
}

function sectionLabel(section) {
  if (section === "library") return "All Media";
  return section.slice(0, 1).toUpperCase() + section.slice(1);
}

function markdownEscape(value) {
  return String(value || "")
    .replace(/\\/g, "\\\\")
    .replace(/\|/g, "\\|")
    .replace(/\r?\n/g, " ");
}

async function mediaStatus(projectDir, relativePath) {
  const cleanPath = normalizePath(relativePath);
  if (!cleanPath) return "missing path";
  try {
    await fs.access(path.join(projectDir, cleanPath));
    return "ok";
  } catch {
    return "missing";
  }
}

async function renderMediaList(projectDir, mediaItems) {
  const rows = [];
  for (const media of Array.isArray(mediaItems) ? mediaItems : []) {
    const cleanPath = normalizePath(media?.path);
    const status = await mediaStatus(projectDir, cleanPath);
    const label = media?.label ? `${media.label}: ` : "";
    rows.push(`${status === "ok" ? "" : "MISSING "}${label}${cleanPath || "(no path)"}`);
  }
  return rows.length ? rows.join("<br>") : "(none)";
}

async function buildSectionRows(projectDir, project, section) {
  const entries = Array.isArray(project?.[section]) ? project[section] : [];
  const rows = [];
  for (const entry of entries) {
    const media = Array.isArray(entry?.media) ? entry.media : [];
    const canonical = await renderMediaList(projectDir, media.slice(0, 1));
    const variants = await renderMediaList(projectDir, media.slice(1));
    rows.push(
      `| ${markdownEscape(displayName(entry))} | ${markdownEscape(entry?.id || "")} | ${markdownEscape(canonical)} | ${markdownEscape(variants)} |`,
    );
  }
  return rows;
}

async function buildAssetManifest(projectDir, project) {
  const lines = [
    "# Anvil Asset Index",
    "",
    "<!-- AUTO-GENERATED BY ANVIL. Do not edit by hand. -->",
    "",
    "This file is generated from Anvil card state so external agents can use the same asset bindings the UI shows.",
    "",
    "## Agent Rules",
    "",
    "- Treat card bindings below as the source of truth for character/location/prop/keyframe/audio references.",
    "- Do not pick media by guessing from `ls assets/...`; use the card name and bound path listed here.",
    "- Files in subfolders can exist in the media index without being cards. A file matters to a card only when it appears below.",
    "- Do not shell-move or delete bound media paths. Use Anvil UI or a dedicated Anvil repair path; generic file tools must not edit `.forge/project.json`.",
    "- If a bound path is marked `MISSING`, ask before repairing unless the user explicitly requested repair.",
    "",
  ];

  for (const section of ASSET_MANIFEST_SECTIONS) {
    const rows = await buildSectionRows(projectDir, project, section);
    lines.push(`## ${sectionLabel(section)}`, "");
    if (!rows.length) {
      lines.push("_No cards._", "");
      continue;
    }
    lines.push("| Card | ID | Bound media | Variants / alternates |");
    lines.push("| --- | --- | --- | --- |");
    lines.push(...rows);
    lines.push("");
  }

  return `${lines.join("\n").replace(/\n+$/g, "")}\n`;
}

async function writeAssetManifest(projectDir, project) {
  const absolutePath = path.join(projectDir, ASSET_MANIFEST_PATH);
  const next = await buildAssetManifest(projectDir, project);
  try {
    const current = await fs.readFile(absolutePath, "utf8");
    if (current === next) {
      return { path: ASSET_MANIFEST_PATH, bytes: Buffer.byteLength(next), changed: false };
    }
  } catch (error) {
    if (error?.code !== "ENOENT") throw error;
  }
  await fs.mkdir(path.dirname(absolutePath), { recursive: true });
  await atomicWriteFile(absolutePath, next);
  return { path: ASSET_MANIFEST_PATH, bytes: Buffer.byteLength(next), changed: true };
}

module.exports = {
  ASSET_MANIFEST_PATH,
  buildAssetManifest,
  writeAssetManifest,
};
